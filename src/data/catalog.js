export const searchProducts = (list, query) => {
  const term = query.trim().toLowerCase();
  if (!term) return list;
  return list.filter((product) => {
    const haystack = [
      product.name,
      product.short,
      product.description,
      product.category,
      product.materials,
      product.sku,
      ...(product.occasions || []),
      ...(product.details || []),
    ]
      .join(" ")
      .toLowerCase();
    return term.split(/\s+/).every((word) => haystack.includes(word));
  });
};

export const filterCatalog = (list, { category = "all", occasion = "all", filter = "all", min = 0, max = priceBounds.max, query = "" }) =>
  searchProducts(list, query).filter((product) => {
    const matchesCategory = category === "all" || product.category === category;
    const matchesOccasion = occasion === "all" || product.occasions.includes(occasion);
    const matchesFilter =
      filter === "all" ||
      (filter === "new" && product.isNew) ||
      (filter === "best" && product.bestseller);
    const matchesPrice = product.price >= Number(min) && product.price <= Number(max);
    return matchesCategory && matchesOccasion && matchesFilter && matchesPrice;
  });

export const sortCatalog = (list, sort) => {
  const next = [...list];
  if (sort === "price-asc") next.sort((a, b) => a.price - b.price);
  else if (sort === "price-desc") next.sort((a, b) => b.price - a.price);
  else if (sort === "name") next.sort((a, b) => a.name.localeCompare(b.name));
  else if (sort === "rating") next.sort((a, b) => b.rating - a.rating || b.reviews - a.reviews);
  else if (sort === "newest") next.sort((a, b) => Number(b.isNew) - Number(a.isNew) || b.reviews - a.reviews);
  else if (sort === "bestselling") next.sort((a, b) => Number(b.bestseller) - Number(a.bestseller) || b.reviews - a.reviews);
  else next.sort((a, b) => Number(b.bestseller) - Number(a.bestseller) || b.rating - a.rating);
  return next;
};
